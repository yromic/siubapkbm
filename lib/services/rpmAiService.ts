export interface RPMGenerateParams {
  mataPelajaran: string;
  kelasRombel: string;
  tingkatFase: string;
  alokasiWaktu: number; // in minutes
  modulTopik: string;
  userId?: string;
  // Authoritative context — passed in, NOT generated by AI
  semester?: string;       // e.g. "Ganjil"
  academicYear?: string;   // e.g. "2026/2027"
  capaianPembelajaran?: string;  // existing CP if already selected
  tujuanPembelajaran?: string[]; // existing TP list if already selected
  karakterFitrah?: string[];     // selected character values (for rubric generation)
}

export interface RPMContent {
  identitas: {
    mataPelajaran: string;
    kelasRombel: string;
    tingkatFase: string;
    /** Human-readable snapshot for print. Source = master semester, NOT AI-generated. */
    semesterTahun?: string;
    /** Actual semester ID from master data */
    semesterId?: string;
    /** Academic year string snapshot */
    tahunAjaran?: string;
    alokasiWaktu: number;
    modulTopik: string;
    trisulaKompetensi: string[];
    deskripsiTrisula: { literasi: string; numerasi: string; diniyyah: string };
    karakterFitrah: string[];
    budayaSahabat: string[];
    dplUtsman: string[];
    dplKurnas: string[];
    namaTutorPengampu?: string;
  };
  desainPembelajaran: {
    capaianPembelajaran: string;
    pemahamanBermakna: string;
    tujuanPembelajaran: string[];
    /** Open-ended questions to stimulate curiosity — 2-3 items */
    pertanyaanPemantik?: string[];
    /** Concrete teaching media/tools — 3-5 items */
    mediaAjar?: string[];
    /** Realistic learning sources — 3-5 items */
    sumberBelajar?: string[];
    kegiatanPembelajaran: {
      awal: RPMActivityInput[];
      inti: RPMActivityInput[];
      akhir: RPMActivityInput[];
      /** Optional structured metadata for each phase */
      metadata?: RPMKegiatanMetadata;
    };
    asesmen: {
      awal: string;
      formatif: string;
      sumatif: string;
      pesanEdukasiOrangTua: string;
      /** Character observation rubric derived from selected karakterFitrah */
      rubrikKarakterFitrah?: RPMRubrikItem[];
    };
  };
}

export interface RPMGenerationResult {
  source: AIGenerationSource;
  content: RPMContent;
  fallbackReason?: AIFallbackReason;
  usage?: AIUsageSnapshot;
}


