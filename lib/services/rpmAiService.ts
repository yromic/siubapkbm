export async function generateRPMContentWithAI(params: RPMGenerateParams): Promise<RPMGenerationResult> {
  const { apiKey, model, endpointUrl } = getGeminiConfig();

  if (!apiKey || !endpointUrl) {
    return getFallbackLocalRPMTemplate(params, 'NO_API_KEY');
  }

  // 1. Guard check local RPM & RPD limits
  const usageCheck = await checkAIUsageLimit(model);
  if (!usageCheck.allowed && usageCheck.blockedReason) {
    await recordAIUsageAttempt({
      userId: params.userId,
      feature: 'RPM_GENERATOR',
      model,
      source: 'FALLBACK',
      providerErrorReason: usageCheck.blockedReason,
      retryAttempt: 1,
    });
    return getFallbackLocalRPMTemplate(params, usageCheck.blockedReason, usageCheck.snapshot);
  }

  const awalTime = 10;
  const akhirTime = 10;
  const resolvedIntiTime = Math.max(params.alokasiWaktu - awalTime - akhirTime, 10);

  // Build rubric character list for AI context
  const karakterForRubric = params.karakterFitrah && params.karakterFitrah.length > 0
    ? params.karakterFitrah
    : ["Keimanan", "Kemandirian", "Adab & Akhlak", "Kreativitas"];

  const contextInfo = [
    params.semester ? `- Semester: ${params.semester}` : '',
    params.academicYear ? `- Tahun Ajaran: ${params.academicYear}` : '',
    params.capaianPembelajaran ? `- CP yang sudah dipilih: ${params.capaianPembelajaran.substring(0, 200)}` : '',
    params.tujuanPembelajaran && params.tujuanPembelajaran.length > 0
      ? `- TP yang sudah ada: ${params.tujuanPembelajaran.slice(0, 3).join('; ')}` : '',
  ].filter(Boolean).join('\n');

  const prompt = `
Anda adalah pakar penyusun Rencana Pemelajaran (RPM) Kurikulum SIUBA / Kurikulum Merdeka Terpadu.
Buatkan rancangan RPM terstruktur dalam format JSON murni tanpa markdown wrapper untuk data berikut:
- Mata Pelajaran: ${params.mataPelajaran}
- Kelas / Rombel: ${params.kelasRombel}
- Tingkat / Fase: ${params.tingkatFase}
- Alokasi Waktu: ${params.alokasiWaktu} Menit (Awal: ${awalTime} + Inti: ${resolvedIntiTime} + Penutup: ${akhirTime})
- Topik / Modul: ${params.modulTopik}
${contextInfo ? `\nKONTEKS RESMI (JANGAN DIUBAH AI):\n${contextInfo}` : ''}

ATURAN PENTING & DETAILED REQUIREMENTS (WAJIB DIPATUHI SANGAT KETAT):
1. trisulaKompetensi: SELALU sertakan ketiga pilar baku: ${JSON.stringify(VALID_TRISULA)}
2. deskripsiTrisula: Tulis penjelasan lengkap 1 PARAGRAF UTUH untuk masing-masing pilar ("literasi", "numerasi", "diniyyah"). Penjelasan harus mengintegrasikan topik "${params.modulTopik}" secara mendalam, ilmiah, dan bernilai Diniyyah/Islamiah (bukan cuma 1 kalimat pendek).
3. karakterFitrah: Pilih 4-5 nilai (generous) yang PALING relevan untuk topik ini dari: ${JSON.stringify(VALID_FITRAH)}
4. budayaSahabat: Pilih 4-5 nilai (generous) yang PALING relevan untuk topik ini dari: ${JSON.stringify(VALID_SAHABAT)}
5. dplUtsman: Pilih 3-5 nilai (generous) yang PALING relevan untuk topik ini dari: ${JSON.stringify(VALID_UTSMAN)}
6. dplKurnas: Pilih 4-5 nilai (generous) dari DAFTAR BAKU INI (JANGAN MENGARANG NILAI BARU): ${JSON.stringify(VALID_KURNAS)}
7. kegiatanPembelajaran: Terdiri dari objek "awal", "inti", "akhir". Setiap item HARUS BERUPA OBJECT:
   { "teks": "Deskripsi rinci langkah aktivitas", "tagBudaya": ["Nama Tag"], "tagKarakter": ["Nama Tag"] }
   - "tagBudaya": 1-2 tag relevan dari daftar budayaSahabat
   - "tagKarakter": 1-2 tag relevan dari daftar karakterFitrah/dplUtsman/dplKurnas
8. kegiatanPembelajaran.metadata: Isi durasi terstruktur TEPAT:
   - awal.durasiMenit: ${awalTime}
   - inti.durasiMenit: ${resolvedIntiTime}
   - akhir.durasiMenit: ${akhirTime}
   - Total HARUS = ${params.alokasiWaktu} menit
9. pertanyaanPemantik: Buat TEPAT 2-3 pertanyaan terbuka (open-ended) yang:
   - Merangsang rasa ingin tahu
   - Sesuai usia/fase siswa
   - Terhubung dengan topik
   - BUKAN pertanyaan ujian (bukan: "Apa itu X?")
   - Boleh terhubung dengan nilai FITRAH/Islam secara alami, JANGAN dipaksakan di setiap pertanyaan
10. mediaAjar: Buat 3-5 rekomendasi media/sarana pembelajaran yang:
    - Konkret dan praktis untuk lingkungan sekolah/pesantren
    - Sesuai dengan mapel "${params.mataPelajaran}", fase "${params.tingkatFase}", topik "${params.modulTopik}"
    - JANGAN rekomendasikan alat mahal atau tidak realistis
    - Contoh: LKPD, flashcard, model visual, alat percobaan sederhana, gambar/poster, peta konsep
11. sumberBelajar: Buat 3-5 sumber belajar realistis:
    - Preferensikan sumber yang tersedia: modul sekolah, buku paket, lingkungan sekitar, observasi
    - Al-Qur'an/Hadits HANYA jika relevan dengan konteks mata pelajaran
    - JANGAN mengarang judul buku spesifik dengan edisi/penulis jika tidak ada dalam konteks
    - Nama generik lebih aman: "Buku teks mapel", "Modul SIUBA", dll.
12. asesmen: Buat kriteria SPESIFIK ke topik "${params.modulTopik}" (BUKAN generik)
13. rubrikKarakterFitrah: Buat baris rubrik untuk SETIAP karakter dalam daftar ini: ${JSON.stringify(karakterForRubric)}
    - Setiap baris: { "indikator": "<nama karakter>", "sangatBaik": "<deskriptor perilaku konkret>", "perluBimbingan": "<deskriptor perilaku konkret>" }
    - Deskriptor HARUS berupa perilaku OBSERVABLE (dapat diamati), bukan abstrak
    - CONTOH BAIK: "Menyelesaikan tugas mandiri dengan teliti dan bertanggung jawab"
    - CONTOH BURUK: "Memiliki jiwa yang luar biasa"

Kembalikan respon DALAM FORMAT JSON PRESIS DENGAN STRUKTUR BERIKUT:
{
  "identitas": {
    "mataPelajaran": "${params.mataPelajaran}",
    "kelasRombel": "${params.kelasRombel}",
    "tingkatFase": "${params.tingkatFase}",
    "alokasiWaktu": ${params.alokasiWaktu},
    "modulTopik": "${params.modulTopik}",
    "trisulaKompetensi": ["Literasi", "Numerasi", "Diniyyah"],
    "deskripsiTrisula": {
      "literasi": "Paragraf lengkap...",
      "numerasi": "Paragraf lengkap...",
      "diniyyah": "Paragraf lengkap..."
    },
    "karakterFitrah": ["...", "..."],
    "budayaSahabat": ["...", "..."],
    "dplUtsman": ["...", "..."],
    "dplKurnas": ["...", "..."]
  },
  "desainPembelajaran": {
    "capaianPembelajaran": "...",
    "pemahamanBermakna": "...",
    "tujuanPembelajaran": ["...", "...", "..."],
    "pertanyaanPemantik": ["Pertanyaan 1?", "Pertanyaan 2?", "Pertanyaan 3?"],
    "mediaAjar": ["Media 1", "Media 2", "Media 3", "Media 4", "Media 5"],
    "sumberBelajar": ["Sumber 1", "Sumber 2", "Sumber 3", "Sumber 4"],
    "kegiatanPembelajaran": {
      "awal": [{ "teks": "...", "tagBudaya": ["Disiplin"], "tagKarakter": ["Adab & Akhlak"] }],
      "inti": [
        { "teks": "...", "tagBudaya": ["Jujur"], "tagKarakter": ["Kemandirian"] },
        { "teks": "...", "tagBudaya": ["Tanggung Jawab"], "tagKarakter": ["Kreativitas"] }
      ],
      "akhir": [{ "teks": "...", "tagBudaya": ["Jujur"], "tagKarakter": ["Adab & Akhlak"] }],
      "metadata": {
        "awal": { "fokus": "Pembukaan dan apersepsi", "durasiMenit": ${awalTime}, "fokusAdab": "Adab berdoa dan menghormati guru" },
        "inti": { "fokus": "Eksplorasi dan latihan", "durasiMenit": ${resolvedIntiTime}, "pendekatanMetode": "Pembelajaran kooperatif kontekstual" },
        "akhir": { "fokus": "Refleksi dan penutupan", "durasiMenit": ${akhirTime}, "fokusRefleksi": "Hikmah pembelajaran dan adab penutup" }
      }
    },
    "asesmen": {
      "awal": "...",
      "formatif": "...",
      "sumatif": "...",
      "pesanEdukasiOrangTua": "...",
      "rubrikKarakterFitrah": [
        { "indikator": "${karakterForRubric[0] || 'Keimanan'}", "sangatBaik": "...", "perluBimbingan": "..." }
      ]
    }
  }
}
  `.trim();

  const maxRetries = 2;
  let attempt = 0;
  let lastFallbackReason: AIFallbackReason = 'UNKNOWN';

  while (attempt < maxRetries) {
    attempt++;
    const reqStartedAt = new Date();
    const controller = new AbortController();
    const timeoutId = setTimeout(() => controller.abort(), 30000);

    try {
      const response = await fetch(endpointUrl, {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        signal: controller.signal,
        body: JSON.stringify({
          contents: [{ parts: [{ text: prompt }] }],
        }),
      });

      clearTimeout(timeoutId);
      const durationMs = Date.now() - reqStartedAt.getTime();

      if (response.status === 429) {
        const rawErrText = await response.text().catch(() => '');
        const classified = classifyProvider429(response.status, rawErrText);
        lastFallbackReason = classified;

        await recordAIUsageAttempt({
          userId: params.userId,
          feature: 'RPM_GENERATOR',
          model,
          source: 'FALLBACK',
          providerHttpStatus: 429,
          providerErrorReason: classified,
          durationMs,
          retryAttempt: attempt,
          requestStartedAt: reqStartedAt,
        });

        if (classified === 'DAILY_QUOTA') {
          return getFallbackLocalRPMTemplate(params, 'DAILY_QUOTA', usageCheck.snapshot);
        }

        if (attempt < maxRetries) {
          const backoffDelay = Math.pow(2, attempt) * 1000 + Math.random() * 500;
          await new Promise((resolve) => setTimeout(resolve, backoffDelay));
          continue;
        }

        return getFallbackLocalRPMTemplate(params, 'RATE_LIMIT', usageCheck.snapshot);
      }

      if (response.status >= 500) {
        lastFallbackReason = 'HTTP_ERROR';
        await recordAIUsageAttempt({
          userId: params.userId,
          feature: 'RPM_GENERATOR',
          model,
          source: 'FALLBACK',
          providerHttpStatus: response.status,
          providerErrorReason: 'HTTP_ERROR',
          durationMs,
          retryAttempt: attempt,
          requestStartedAt: reqStartedAt,
        });

        if (attempt < maxRetries) {
          const backoffDelay = Math.pow(2, attempt) * 1000;
          await new Promise((resolve) => setTimeout(resolve, backoffDelay));
          continue;
        }
        return getFallbackLocalRPMTemplate(params, 'HTTP_ERROR', usageCheck.snapshot);
      }

      if (!response.ok) {
        await recordAIUsageAttempt({
          userId: params.userId,
          feature: 'RPM_GENERATOR',
          model,
          source: 'FALLBACK',
          providerHttpStatus: response.status,
          providerErrorReason: 'HTTP_ERROR',
          durationMs,
          retryAttempt: attempt,
          requestStartedAt: reqStartedAt,
        });
        return getFallbackLocalRPMTemplate(params, 'HTTP_ERROR', usageCheck.snapshot);
      }

      const data = await response.json();
      const rawText = data.candidates?.[0]?.content?.parts?.[0]?.text || "";
      const cleanedText = rawText.replace(/```json/gi, "").replace(/```/g, "").trim();
      let parsed: RPMContent;

      try {
        parsed = JSON.parse(cleanedText);
      } catch {
        await recordAIUsageAttempt({
          userId: params.userId,
          feature: 'RPM_GENERATOR',
          model,
          source: 'FALLBACK',
          providerHttpStatus: 200,
          providerErrorReason: 'INVALID_JSON',
          durationMs,
          retryAttempt: attempt,
          requestStartedAt: reqStartedAt,
        });
        return getFallbackLocalRPMTemplate(params, 'INVALID_JSON', usageCheck.snapshot);
      }

      if (!parsed.identitas || !parsed.desainPembelajaran) {
        await recordAIUsageAttempt({
          userId: params.userId,
          feature: 'RPM_GENERATOR',
          model,
          source: 'FALLBACK',
          providerHttpStatus: 200,
          providerErrorReason: 'INVALID_SCHEMA',
          durationMs,
          retryAttempt: attempt,
          requestStartedAt: reqStartedAt,
        });
        return getFallbackLocalRPMTemplate(params, 'INVALID_SCHEMA', usageCheck.snapshot);
      }

      // Sanitize dplKurnas
      if (Array.isArray(parsed.identitas?.dplKurnas)) {
        parsed.identitas.dplKurnas = parsed.identitas.dplKurnas.filter(
          (v: string) => (VALID_KURNAS as readonly string[]).includes(v)
        );
        if (parsed.identitas.dplKurnas.length === 0) {
          parsed.identitas.dplKurnas = ["Penalaran Kritis", "Kemandirian"];
        }
      }

      // Ensure trisulaKompetensi has all three pillars
      if (!parsed.identitas.trisulaKompetensi || parsed.identitas.trisulaKompetensi.length === 0) {
        parsed.identitas.trisulaKompetensi = ["Literasi", "Numerasi", "Diniyyah"];
      }

      // Guard: AI must not override authoritative context fields
      if (params.capaianPembelajaran) {
        parsed.desainPembelajaran.capaianPembelajaran = params.capaianPembelajaran;
      }
      if (params.tujuanPembelajaran && params.tujuanPembelajaran.length > 0) {
        parsed.desainPembelajaran.tujuanPembelajaran = params.tujuanPembelajaran;
      }

      // Sanitize rubrik: ensure it corresponds to selected karakterFitrah
      const expectedKarakter = new Set(karakterForRubric);
      const existingRubrik = Array.isArray(parsed.desainPembelajaran?.asesmen?.rubrikKarakterFitrah)
        ? parsed.desainPembelajaran.asesmen.rubrikKarakterFitrah
        : [];
      const existingMap = new Map(existingRubrik.map((r: RPMRubrikItem) => [r.indikator, r]));

      const sanitizedRubrik: RPMRubrikItem[] = karakterForRubric.map((k) => {
        if (existingMap.has(k)) return existingMap.get(k)!;
        return {
          indikator: k,
          sangatBaik: `Santri menunjukkan sikap ${k.toLowerCase()} secara konsisten dan mandiri dalam kegiatan pembelajaran.`,
          perluBimbingan: `Santri belum menunjukkan sikap ${k.toLowerCase()} secara konsisten dan memerlukan bimbingan lanjutan.`,
        };
      });

      if (parsed.desainPembelajaran?.asesmen) {
        parsed.desainPembelajaran.asesmen.rubrikKarakterFitrah = sanitizedRubrik;
      }

      // Ensure arrays for new fields
      if (!Array.isArray(parsed.desainPembelajaran?.pertanyaanPemantik)) {
        parsed.desainPembelajaran.pertanyaanPemantik = [];
      }
      if (!Array.isArray(parsed.desainPembelajaran?.mediaAjar)) {
        parsed.desainPembelajaran.mediaAjar = [];
      }
      if (!Array.isArray(parsed.desainPembelajaran?.sumberBelajar)) {
        parsed.desainPembelajaran.sumberBelajar = [];
      }

      // Record successful GEMINI attempt
      await recordAIUsageAttempt({
        userId: params.userId,
        feature: 'RPM_GENERATOR',
        model,
        source: 'GEMINI',
        providerHttpStatus: 200,
        durationMs,
        retryAttempt: attempt,
        requestStartedAt: reqStartedAt,
      });

      return {
        source: 'GEMINI',
        content: parsed,
        usage: usageCheck.snapshot,
      };
    } catch (err: any) {
      clearTimeout(timeoutId);
      lastFallbackReason = controller.signal.aborted ? 'TIMEOUT' : 'NETWORK_ERROR';
      const durationMs = Date.now() - reqStartedAt.getTime();

      await recordAIUsageAttempt({
        userId: params.userId,
        feature: 'RPM_GENERATOR',
        model,
        source: 'FALLBACK',
        providerErrorReason: lastFallbackReason,
        durationMs,
        retryAttempt: attempt,
        requestStartedAt: reqStartedAt,
      });

      if (attempt >= maxRetries) {
        return getFallbackLocalRPMTemplate(params, lastFallbackReason, usageCheck.snapshot);
      }
      const backoffDelay = Math.pow(2, attempt) * 1000;
      await new Promise((resolve) => setTimeout(resolve, backoffDelay));
    }
  }

  return getFallbackLocalRPMTemplate(params, lastFallbackReason, usageCheck.snapshot);
}

